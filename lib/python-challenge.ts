// Builds and reads the auto-graded Python course challenges.
// The course UI (browser Python, see lib/browser-python.ts) and the offline verifiers (local CPython)
// both use buildChallengeScript, so a challenge is graded by exactly the same script everywhere.
// It prints a JSON report between the markers below, plus "@@IVOS_*" progress lines so a check that
// hangs in the browser can be stopped and reported without losing the results before it.

export const CHALLENGE_START_MARKER = "JSON_OUTPUT_START";
export const CHALLENGE_END_MARKER = "JSON_OUTPUT_END";
/** Seconds a single check may take on local CPython. Browser Python is slower, so it gets more. */
export const CHECK_TIMEOUT_SECONDS = 2;
export const BROWSER_CHECK_TIMEOUT_SECONDS = 6;
/** Seconds after start when remaining checks are skipped (local CPython / browser). */
export const RUN_BUDGET_SECONDS = 4.5;
export const BROWSER_RUN_BUDGET_SECONDS = 40;
/** The page stops a browser check that is still running this long after it started (it cannot be interrupted from inside). */
export const BROWSER_CHECK_KILL_MS = (BROWSER_CHECK_TIMEOUT_SECONDS + 4) * 1000;
/** Lines the harness prints for the page's watchdog. */
export const PROGRESS_PREFIX = "@@IVOS_";

export interface ChallengeCheckResult { name: string; passed: boolean; error?: string; output?: string }
export interface ChallengeReport {
  allPassed: boolean;
  results: ChallengeCheckResult[];
  /** Error raised while your code was loading (syntax errors, top-level exceptions). */
  loadError?: string;
  /** Problem with the lesson's checks themselves. */
  error?: string;
  /** Output printed while your code was loading. */
  output?: string;
}
export interface ExecuteResponse { success?: boolean; exitCode?: number | null; runtimeMs?: number; stdout?: string; stderr?: string; testResults?: unknown; timeout?: boolean; error?: string }

/** A Python string literal for `text` that is pure ASCII (\uXXXX / \UXXXXXXXX escapes for everything else). */
function pythonString(text: string): string {
  return JSON.stringify(text.replace(/\r\n?/g, "\n")).replace(/[^\x00-\x7f]/gu, char => {
    const point = char.codePointAt(0)!;
    return point > 0xffff ? `\\U${point.toString(16).padStart(8, "0")}` : `\\u${point.toString(16).padStart(4, "0")}`;
  });
}

/**
 * Returns a complete Python script: it executes `userCode` as the main module (so functions stay
 * picklable for multiprocessing's spawn start method), then runs every `@check("name")` function from
 * `tests` in its own thread with a timeout, and prints a JSON report between the output markers.
 * Inside `tests`, user names are globals and the helpers `check`, `eq(actual, expected)` and
 * `raises(ExceptionType, func, *args, **kwargs)` are available.
 */
export function buildChallengeScript(userCode: string, tests: string): string {
  return String.raw`# Generated by InterviewOS: runs your code, then the lesson's checks.
import sys as _ivos_sys
import time as _ivos_time

_ivos_started = _ivos_time.perf_counter()

import contextlib as _ivos_contextlib
import io as _ivos_io
import json as _ivos_json
import linecache as _ivos_linecache
import os as _ivos_os
import traceback as _ivos_traceback

for _ivos_stream in (_ivos_sys.stdout, _ivos_sys.stderr):
    try:
        _ivos_stream.reconfigure(encoding="utf-8", errors="backslashreplace")
    except Exception:
        pass
_ivos_sys.stdin = _ivos_io.StringIO("")

_IVOS_SOLUTION = ${pythonString(userCode)}
_IVOS_CHECKS = ${pythonString(tests)}
_IVOS_BROWSER = _ivos_sys.platform == "emscripten"
_IVOS_CHECK_TIMEOUT = ${BROWSER_CHECK_TIMEOUT_SECONDS} if _IVOS_BROWSER else ${CHECK_TIMEOUT_SECONDS}
_IVOS_BUDGET = ${BROWSER_RUN_BUDGET_SECONDS} if _IVOS_BROWSER else ${RUN_BUDGET_SECONDS}
_ivos_stream = _ivos_sys.stdout  # captured before any redirection
_IVOS_SOURCES = ("solution.py", "checks.py")


def _ivos_compile(source, filename):
    _ivos_linecache.cache[filename] = (len(source), None, source.splitlines(True), filename)
    return compile(source, filename, "exec")


def _ivos_clip(text, limit=3000):
    text = str(text)
    return text if len(text) <= limit else text[:limit] + "\n... [truncated]"


def _ivos_describe(error):
    frames = [frame for frame in _ivos_traceback.extract_tb(error.__traceback__) if frame.filename in _IVOS_SOURCES]
    if isinstance(error, AssertionError) and (not frames or frames[-1].filename == "checks.py"):
        message = str(error)
        if not message and frames:
            message = "Check failed: " + (frames[-1].line or "assertion")
        return _ivos_clip(message or "Check failed.")
    lines = _ivos_traceback.format_exception_only(type(error), error)
    if frames:
        lines = ["Traceback (most recent call last):\n"] + _ivos_traceback.format_list(frames) + lines
    return _ivos_clip("".join(lines).rstrip())


# Your code runs as this module's top level, exactly as if it were the whole file.
_ivos_load_error = None
_ivos_load_output = _ivos_io.StringIO()
try:
    with _ivos_contextlib.redirect_stdout(_ivos_load_output), _ivos_contextlib.redirect_stderr(_ivos_load_output):
        exec(_ivos_compile(_IVOS_SOLUTION, "solution.py"), globals())
except BaseException as _ivos_error:
    _ivos_load_error = _ivos_describe(_ivos_error)


def _ivos_short(value, limit=300):
    try:
        text = repr(value)
    except Exception:
        text = "<unrepresentable %s>" % type(value).__name__
    return text if len(text) <= limit else text[:limit] + "..."


def _ivos_eq(actual, expected, message=None):
    if not (actual == expected):
        raise AssertionError(message or "expected %s, got %s" % (_ivos_short(expected), _ivos_short(actual)))


def _ivos_raises(expected, func, *args, **kwargs):
    kinds = expected if isinstance(expected, tuple) else (expected,)
    names = " or ".join(kind.__name__ for kind in kinds)
    try:
        func(*args, **kwargs)
    except expected as error:
        return error
    except Exception as error:
        raise AssertionError("expected %s, but got %s: %s" % (names, type(error).__name__, error)) from error
    raise AssertionError("expected %s, but nothing was raised" % names)


def _ivos_progress(kind, payload):
    _ivos_stream.write("\n@@IVOS_%s %s\n" % (kind, _ivos_json.dumps(payload)))
    _ivos_stream.flush()


def _ivos_run(func, limit):
    """Run one check and time it; returns None if it was still running after limit seconds.

    Local Python runs the check in a thread so a hung check can time out. Browser Python has no
    threads, so the check runs inline and the page stops the worker if it hangs.
    """
    outcome = {}

    def target():
        started = _ivos_time.perf_counter()
        try:
            func()
        except BaseException as error:
            outcome["error"] = error
        outcome["elapsed"] = _ivos_time.perf_counter() - started

    if _IVOS_BROWSER:
        target()
        return outcome
    import threading
    worker = threading.Thread(target=target, name="lesson-check", daemon=True)
    worker.start()
    worker.join(limit)
    return None if worker.is_alive() else outcome


def _ivos_main():
    checks = []

    def check(name):
        def register(func):
            checks.append((str(name), func))
            return func
        return register

    namespace = dict(globals())
    namespace.update(check=check, eq=_ivos_eq, raises=_ivos_raises)
    report = {"kind": "python-challenge", "version": 1, "results": []}
    output = _ivos_load_output.getvalue()
    if output:
        report["output"] = _ivos_clip(output, 2000)
    if _ivos_load_error is not None:
        report["loadError"] = _ivos_load_error
    try:
        exec(_ivos_compile(_IVOS_CHECKS, "checks.py"), namespace)
    except BaseException as error:
        report["error"] = "The lesson's checks could not be loaded:\n" + _ivos_describe(error)
    _ivos_progress("CHECKS", [name for name, _ in checks])
    for name, func in checks:
        entry = {"name": name, "passed": False}
        remaining = _IVOS_BUDGET - (_ivos_time.perf_counter() - _ivos_started)
        if _ivos_load_error is not None:
            entry["error"] = "Not run: your code raised an error before the checks started."
        elif remaining < 0.1:
            entry["error"] = "Not run: earlier checks used up this run's time budget."
        else:
            limit = min(_IVOS_CHECK_TIMEOUT, remaining)
            buffer = _ivos_io.StringIO()
            _ivos_progress("RUN", len(report["results"]))
            with _ivos_contextlib.redirect_stdout(buffer), _ivos_contextlib.redirect_stderr(buffer):
                outcome = _ivos_run(func, limit)
            if outcome is None:
                entry["error"] = "Timed out after %.1fs. Look for an infinite loop, a missing join or sentinel, or an algorithm slower than the lesson asks for." % limit
            elif "error" in outcome:
                entry["error"] = _ivos_describe(outcome["error"])
            elif outcome["elapsed"] > limit:
                entry["error"] = "Too slow: took %.1fs (limit %.1fs). Look for an algorithm slower than the lesson asks for." % (outcome["elapsed"], limit)
            else:
                entry["passed"] = True
            text = buffer.getvalue()
            if text:
                entry["output"] = _ivos_clip(text, 1500)
        report["results"].append(entry)
        _ivos_progress("DONE", entry)
    results = report["results"]
    report["allPassed"] = bool(results) and all(entry["passed"] for entry in results) and "error" not in report and "loadError" not in report
    stream = _ivos_stream
    stream.write("\n${CHALLENGE_START_MARKER}\n" + _ivos_json.dumps(report) + "\n${CHALLENGE_END_MARKER}\n")
    stream.flush()
    if not _IVOS_BROWSER:
        # Run from a terminal (a downloaded challenge), a readable summary goes to stderr too.
        lines = [report.get("loadError") or "", report.get("error") or ""]
        for entry in results:
            lines.append(("PASS  " if entry["passed"] else "FAIL  ") + entry["name"] + ("" if entry["passed"] else "\n      " + str(entry.get("error", "")).replace("\n", "\n      ")))
        lines.append("\nAll checks passed." if report["allPassed"] else "\n%d of %d checks passed." % (sum(entry["passed"] for entry in results), len(results)))
        _ivos_sys.stderr.write("\n".join(line for line in lines if line) + "\n")
        _ivos_sys.stderr.flush()
        # Exit at once so a thread the learner's code left running can't hold the process open.
        _ivos_os._exit(0)


if __name__ == "__main__":
    _ivos_main()
`;
}

function text(value: unknown): string | undefined {
  return typeof value === "string" && value ? value : undefined;
}

/** Validates a parsed report produced by buildChallengeScript; returns null for anything else. */
export function parseChallengeReport(raw: unknown): ChallengeReport | null {
  if (!raw || typeof raw !== "object") return null;
  const value = raw as Record<string, unknown>;
  if (value.kind !== "python-challenge" || !Array.isArray(value.results)) return null;
  const results: ChallengeCheckResult[] = value.results.flatMap(item => {
    if (!item || typeof item !== "object") return [];
    const entry = item as Record<string, unknown>;
    return [{ name: String(entry.name ?? "Check"), passed: entry.passed === true, error: text(entry.error), output: text(entry.output) }];
  });
  const loadError = text(value.loadError);
  const error = text(value.error);
  return { allPassed: value.allPassed === true && results.length > 0 && results.every(item => item.passed) && !loadError && !error, results, loadError, error, output: text(value.output) };
}

/**
 * When the page had to stop a run (a check hung), there is no final report. Rebuild one from the
 * progress lines: finished checks keep their results, the running one is marked as stopped.
 */
export function partialChallengeReport(stdout: string, reason: string): ChallengeReport | null {
  let names: string[] | null = null;
  const done: ChallengeCheckResult[] = [];
  let running = -1;
  for (const line of stdout.split("\n")) {
    if (!line.startsWith(PROGRESS_PREFIX)) continue;
    const space = line.indexOf(" ");
    const kind = line.slice(PROGRESS_PREFIX.length, space);
    let payload: unknown;
    try { payload = JSON.parse(line.slice(space + 1)); } catch { continue; }
    if (kind === "CHECKS" && Array.isArray(payload)) names = payload.map(String);
    else if (kind === "RUN" && typeof payload === "number") running = payload;
    else if (kind === "DONE") done.push(...(parseChallengeReport({ kind: "python-challenge", results: [payload] })?.results ?? []));
  }
  if (!names) return { allPassed: false, results: [], loadError: `Your code did not finish loading. ${reason} Look for an infinite loop or a blocking call at the top level.` };
  const results = names.map((name, index): ChallengeCheckResult => done[index]
    ?? { name, passed: false, error: index === running ? `Stopped: ${reason} Look for an infinite loop, a missing sentinel, or an algorithm much slower than the lesson asks for.` : "Not run: an earlier check had to be stopped." });
  return { allPassed: false, results };
}

/** Reads the report from a run's response, falling back to the raw stdout markers. */
export function readChallengeReport(response: ExecuteResponse): ChallengeReport | null {
  const parsed = parseChallengeReport(response.testResults);
  if (parsed) return parsed;
  const stdout = response.stdout || "";
  const start = stdout.lastIndexOf(CHALLENGE_START_MARKER);
  const end = start < 0 ? -1 : stdout.indexOf(CHALLENGE_END_MARKER, start);
  if (end >= 0) {
    try { return parseChallengeReport(JSON.parse(stdout.slice(start + CHALLENGE_START_MARKER.length, end))); }
    catch { return null; }
  }
  return response.timeout ? partialChallengeReport(stdout, response.error || "It ran too long.") : null;
}

/**
 * Browser Python (Pyodide) cannot start threads or processes, so challenges that need them are
 * graded by downloading the checks and running them with a local Python instead.
 */
const NEEDS_LOCAL = /\b(threading|multiprocessing|ThreadPoolExecutor|ProcessPoolExecutor|concurrent\.futures)\b/;
export function needsLocalPython(challenge: { tests?: string; solution?: string }): boolean {
  return NEEDS_LOCAL.test(`${challenge.tests ?? ""}\n${challenge.solution ?? ""}`);
}
